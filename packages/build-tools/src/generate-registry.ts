// Registry generator for the Microservice_Registry (design "Registry
// Generator"; Requirements R5.1, R5.2, R5.3, R5.5, R6.1, R6.2, R10.2).
//
// Paths are relative, i.e. resolved against cwd, which is the repo root for
// both `npm start` and the Dockerfile build stage. Errors propagate: Node
// prints them and exits non-zero (R5.4, R5.5, R10.4).

import { mkdirSync, readdirSync, writeFileSync } from "node:fs";
import { dirname } from "node:path";

import { resolveSelected } from "./selector.js";

/** The well-known output path the Overseer imports at build time. */
const OUTPUT_PATH = "packages/overseer/src/generated/microservice-registry.ts";

/**
 * List the candidate microservice directory names, sorted lexicographically.
 *
 * Directory contents are deliberately NOT validated: a directory that is not a
 * usable microservice module fails later, at `tsc` build time, on the generated
 * static import — closer to the actual defect than a discovery-time warning.
 */
export function listMicroserviceDirectories(
  namespacePath = "packages/microservices",
): string[] {
  return readdirSync(namespacePath, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .sort();
}

/**
 * Generate the registry for the selector and write it to {@link OUTPUT_PATH}.
 *
 * Each emitted entry carries the directory name as its `identifier`, so the
 * Overseer reads the authoritative identifier straight off the registry and
 * never parses it back out of `sourcePackage`.
 */
export function generateRegistry(selector = process.env.MICROSERVICES): void {
  const identifiers = resolveSelected(selector, listMicroserviceDirectories());

  const code = `// AUTO-GENERATED by @scaffold/build-tools. Do not edit.
// Selector: ${selector ?? "*"}
${identifiers.map((id, i) => `import * as m${i} from "@scaffold/${id}";`).join("\n")}
import type { MicroserviceRegistry } from "@scaffold/contracts";

// COUPLING NOTE: the empty template at
// packages/overseer/src/generated/microservice-registry.template.ts must match
// this file's export name, type import, and shape. Keep them in sync; the
// typechecker is the safety net.
export const microserviceRegistry: MicroserviceRegistry = [
${identifiers.map((id, i) => `  { identifier: "${id}", module: m${i}, sourcePackage: "@scaffold/${id}" },`).join("\n")}
];
`;

  mkdirSync(dirname(OUTPUT_PATH), { recursive: true });
  writeFileSync(OUTPUT_PATH, code, "utf8");
}
